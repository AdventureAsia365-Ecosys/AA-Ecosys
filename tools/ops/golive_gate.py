# YAML subset parser
# --------------------------------------------------------------------------------------------------------------------

_KEY = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*):(?:[ ](.*))?$")
_PLAIN_BAD_START = tuple("[]{}&*!|>'\"%@`,?:-#")


def _strip_comment(text: str) -> str:
    """Drop a trailing `` # comment`` from an unquoted value."""
    m = re.search(r"(^|\s)#", text)
    return text[:m.start()].rstrip() if m else text.rstrip()


def _quoted(text: str, lineno: int) -> tuple[str, str]:
    """Parse one quoted scalar at the start of text; return (value, rest)."""
    q = text[0]
    if q == '"':
        i = 1
        while i < len(text):
            if text[i] == "\\":
                i += 2
                continue
            if text[i] == '"':
                try:
                    return json.loads(text[:i + 1]), text[i + 1:]
                except json.JSONDecodeError as exc:
                    raise GateError(f"line {lineno}: bad double-quoted string ({exc.msg})") from None
            i += 1
        raise GateError(f"line {lineno}: unterminated double-quoted string")
    out = []
    i = 1
    while i < len(text):
        if text[i] == "'":
            if text[i + 1:i + 2] == "'":
                out.append("'")
                i += 2
                continue
            return "".join(out), text[i + 1:]
        out.append(text[i])
        i += 1
    raise GateError(f"line {lineno}: unterminated single-quoted string")


def _plain(text: str, lineno: int) -> Any:
    if text in ("", "~", "null", "Null", "NULL"):
        return None
    if text in ("true", "True", "TRUE"):
        return True
    if text in ("false", "False", "FALSE"):
        return False
    if re.fullmatch(r"-?[0-9]+", text):
        return int(text)
    if text.startswith(_PLAIN_BAD_START) or ": " in text or text.endswith(":") or "\t" in text:
        raise GateError(f"line {lineno}: quote this value: {text!r}")
    return text


def _scalar(text: str, lineno: int) -> Any:
    text = text.strip()
    if text.startswith(("'", '"')):
        value, rest = _quoted(text, lineno)
        rest = rest.strip()
        if rest and not rest.startswith("#"):
            raise GateError(f"line {lineno}: text after a quoted string: {rest!r}")
        return value
    if text.startswith("["):
        return _flow_list(text, lineno)
    if text.startswith(("{", "|", ">", "&", "*", "!")):
        raise GateError(f"line {lineno}: unsupported YAML construct {text[:1]!r} (use the plain subset)")
    return _plain(_strip_comment(text), lineno)


def _flow_list(text: str, lineno: int) -> list:
    body = text[1:]
    items: list = []
    expect_item = True
    while True:
        body = body.lstrip()
        if not body:
            raise GateError(f"line {lineno}: unterminated [ list")
        if body[0] == "]":
            rest = body[1:].strip()
            if rest and not rest.startswith("#"):
                raise GateError(f"line {lineno}: text after a ] list")
            if not expect_item or not items:
                return items
            raise GateError(f"line {lineno}: empty item in a [ list")
        if body[0] == ",":
            if expect_item:
                raise GateError(f"line {lineno}: empty item in a [ list")
            expect_item = True
            body = body[1:]
            continue
        if not expect_item:
            raise GateError(f"line {lineno}: missing comma in a [ list")
        if body[0] in "'\"":
            value, body = _quoted(body, lineno)
        else:
            m = re.match(r"[^,\]]*", body)
            raw = m.group(0).strip()
            body = body[m.end():]
            value = _plain(raw, lineno)
        items.append(value)
        expect_item = False


def parse_yaml(text: str) -> Any:
    """Parse the YAML subset of the checklist (see the module docstring); GateError with a line number otherwise."""
    lines: list[tuple[int, int, str]] = []  # (line number, indent, content)
    for n, raw in enumerate(text.split("\n"), start=1):
        if "\t" in raw[:len(raw) - len(raw.lstrip())]:
            raise GateError(f"line {n}: tab in indentation")
        stripped = raw.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if stripped in ("---", "..."):
            raise GateError(f"line {n}: one document only, no '---' / '...' markers")
        lines.append((n, len(raw) - len(raw.lstrip(" ")), stripped))
    if not lines:
        raise GateError("empty document")
    value, i = _block(lines, 0, lines[0][1])
    if i != len(lines):
        n, _, content = lines[i]
        raise GateError(f"line {n}: unexpected indentation or content: {content!r}")
    return value


def _is_seq(content: str) -> bool:
    return content == "-" or content.startswith("- ")


def _block(lines: list, i: int, indent: int) -> tuple[Any, int]:
    if _is_seq(lines[i][2]):
        return _sequence(lines, i, indent)
    return _mapping(lines, i, indent)


def _sequence(lines: list, i: int, indent: int) -> tuple[list, int]:
    out: list = []
    while i < len(lines) and lines[i][1] == indent and _is_seq(lines[i][2]):
        n, _, content = lines[i]
        rest = content[1:].strip()
        if not rest:
            if i + 1 >= len(lines) or lines[i + 1][1] <= indent:
                out.append(None)
                i += 1
                continue
            value, i = _block(lines, i + 1, lines[i + 1][1])
            out.append(value)
        elif _KEY.match(rest):
            # "- key: value" opens a mapping whose keys sit two columns right of the dash
            lines[i] = (n, indent + 2, rest)
            value, i = _mapping(lines, i, indent + 2)
            out.append(value)
        else:
            out.append(_scalar(rest, n))
            i += 1
    return out, i


def _mapping(lines: list, i: int, indent: int) -> tuple[dict, int]:
    out: dict = {}
    while i < len(lines) and lines[i][1] == indent and not _is_seq(lines[i][2]):
        n, _, content = lines[i]
        m = _KEY.match(content)
        if not m:
            raise GateError(f"line {n}: expected 'key: value', got {content!r}")
        key, raw = m.group(1), (m.group(2) or "")
        if key in out:
            raise GateError(f"line {n}: duplicate key {key!r}")
        if _strip_comment(raw) == "" and not raw.strip().startswith(("'", '"')):
            nxt = lines[i + 1] if i + 1 < len(lines) else None
            if nxt and (nxt[1] > indent or (nxt[1] == indent and _is_seq(nxt[2]))):
                value, i = _block(lines, i + 1, nxt[1])
            else:
                value, i = None, i + 1
        else:
            value, i = _scalar(raw, n), i + 1
        out[key] = value
    if i < len(lines) and lines[i][1] > indent:
        raise GateError(f"line {lines[i][0]}: unexpected indentation")
    return out, i


