# ── loading ─────────────────────────────────────────────────────────────────────────────────────────────────────────


def load(root: Path = REPO_ROOT, path: str = CALENDAR) -> dict:
    try:
        doc = parse_yaml((root / path).read_text(encoding="utf-8"))
    except GateError as exc:
        raise CalendarError(f"{path}: {exc}") from None
    if not isinstance(doc, dict):
        raise CalendarError(f"{path}: the calendar must be a mapping")
    return doc


def _date(value: Any) -> Optional[date]:
    if isinstance(value, str) and ISO.match(value):
        try:
            return date.fromisoformat(value)
        except ValueError:
            return None
    return None


def add_months(day: date, months: int) -> date:
    y, m = divmod(day.month - 1 + months, 12)
    year, month = day.year + y, m + 1
    return date(year, month, min(day.day, _cal.monthrange(year, month)[1]))


def step(day: date, cadence: str) -> date:
    """One cadence period after ``day``."""
    if cadence == "weekly":
        return day + timedelta(days=7)
    if cadence == "monthly":
        return add_months(day, 1)
    if cadence == "quarterly":
        return add_months(day, 3)
    if cadence == "yearly":
        return add_months(day, 12)
    m = EVERY.match(cadence or "")
    if m:
        return day + timedelta(days=int(m.group(1)))
    raise CalendarError(f"unknown cadence {cadence!r}")


def next_slot(anchor: date, cadence: str, today: date) -> date:
    """The first slot of the series anchor, anchor + 1 period, ... that is on or after today."""
    slot, n = anchor, 0
    while slot < today:
        n += 1
        if cadence in ("monthly", "quarterly", "yearly"):
            slot = add_months(anchor, n * {"monthly": 1, "quarterly": 3, "yearly": 12}[cadence])
        else:
            slot = step(slot, cadence)
    return slot


def evidence_dates(root: Path, pattern: str) -> list[date]:
    """Dates (the first YYYY-MM-DD in each repo-relative path) of the paths the glob matches."""
    out = []
    for hit in glob.glob(str(root / pattern), recursive=True):
        rel = Path(hit).relative_to(root).as_posix()
        m = PATH_DATE.search(rel)
        if m:
            d = _date(m.group(1))
            if d:
                out.append(d)
    return sorted(out)


# ── the registers a line reads its dates from ───────────────────────────────────────────────────────────────────────


def register_dates(root: Path, source: str) -> list[date]:
    """Every due date of one register (unsorted, duplicates kept: one per row)."""
    if source == "secrets-register":
        sec = root / "tools" / "security"
        if str(sec) not in sys.path:
            sys.path.insert(0, str(sec))
        import secrets_register as sr   # noqa: PLC0415 - PyYAML; only when a line reads the register

        try:
            reg = sr.load(root / "docs" / "security" / "secrets-register.yaml")
        except sr.RegisterError as exc:
            raise CalendarError(f"secrets register: {exc}") from None
        out = []
        for entry in sr.schedule(reg):
            r = sr.effective(entry, reg)
            d = _date(r.next_due) or _date(r.expires)
            if d:
                out.append(d)
        return out
    if source == "go-live-checklist":
        doc = parse_yaml((root / CHECKLIST).read_text(encoding="utf-8"))
        out = []
        for it in doc.get("items") or []:
            if isinstance(it, dict) and it.get("kind") == "gate" and not it.get("proof"):
                d = _date(it.get("due"))
                if d:
                    out.append(d)
        return out
    if source == "vuln-exceptions":
        rows = tomllib.loads((root / VULN_EXCEPTIONS).read_text(encoding="utf-8")).get("exception", [])
        return [r["expires"] for r in rows if isinstance(r.get("expires"), date)]
    raise CalendarError(f"unknown dates_from {source!r}")


# ── validation ──────────────────────────────────────────────────────────────────────────────────────────────────────


def _text_problems(where: str, item: dict) -> list[str]:
    errors = []
    for key in ("title", "note", "trigger", "cadence", "source", "evidence"):
        value = item.get(key)
        if not isinstance(value, str):
            continue
        for rx, what in FORBIDDEN:
            if rx.search(value):
                errors.append(f"{where}: {key} carries {what} (public repo)")
        if key in ("title", "note") and "|" in value:
            errors.append(f"{where}: {key} may not contain '|' (the evidence rows are '|'-separated)")
        if key in ("title", "note", "trigger") and ISSUE_ID.search(value):
            errors.append(f"{where}: {key} names an issue id; the CIS tab shows it (put the id in source)")
    return errors


def validate(doc: dict, root: Path = REPO_ROOT) -> list[str]:
    errors: list[str] = []
    unknown = set(doc) - TOP_KEYS
    if unknown:
        errors.append(f"unknown top-level keys: {', '.join(sorted(unknown))}")
    if doc.get("version") != 1:
        errors.append("version must be 1")
    if _date(doc.get("updated")) is None:
        errors.append("updated must be an ISO date (YYYY-MM-DD)")
    items = doc.get("items")
    if not isinstance(items, list) or not items:
        return errors + ["items must be a non-empty list"]
    seen: set[str] = set()
    for pos, item in enumerate(items, start=1):
        where = f"item {pos}"
        if not isinstance(item, dict):
            errors.append(f"{where}: must be a mapping")
            continue
        iid = item.get("id")
        if isinstance(iid, str) and ITEM_ID.match(iid):
            where = iid
            if iid in seen:
                errors.append(f"{iid}: duplicate id")
            seen.add(iid)
        else:
            errors.append(f"{where}: id must look like OC-001")
        for key in sorted(set(item) - ITEM_KEYS):
            errors.append(f"{where}: unknown field {key!r}")
        for key in ("title", "source"):
            if not (isinstance(item.get(key), str) and item[key].strip()):
                errors.append(f"{where}: {key} is required (text)")
        if isinstance(item.get("title"), str) and len(item["title"]) > TITLE_MAX:
            errors.append(f"{where}: title longer than {TITLE_MAX} characters")
        if item.get("owner") not in ROLES:
            errors.append(f"{where}: owner must be one of {', '.join(ROLES)} (roles, never people)")
        if item.get("reminder") not in REMINDERS:
            errors.append(f"{where}: reminder must be one of {', '.join(REMINDERS)}")
        for key in ("anchor", "date", "window_from", "done", "trigger_date"):
            if item.get(key) is not None and _date(item.get(key)) is None:
                errors.append(f"{where}: {key} must be an ISO date (YYYY-MM-DD)")
        for key in ("warn_days", "within_days"):
            v = item.get(key)
            if v is not None and (not isinstance(v, int) or isinstance(v, bool) or v < 0):
                errors.append(f"{where}: {key} must be a whole number of days, 0 or more")
        errors += _text_problems(where, item)
        kind = item.get("kind")
        if kind not in KINDS:
            errors.append(f"{where}: kind must be one of {', '.join(KINDS)}")
            continue
        errors += _validate_kind(where, kind, item, root)
    return errors


def _only(where: str, item: dict, allowed: set[str], kind: str) -> list[str]:
    common = {"id", "kind", "title", "owner", "source", "reminder", "note"}
    return [f"{where}: {key!r} does not apply to a {kind} line" for key in sorted(set(item) - common - allowed)]


def _validate_kind(where: str, kind: str, item: dict, root: Path) -> list[str]:
    errors: list[str] = []
    needs_warn = False
    if kind == "recurring":
        errors += _only(where, item, {"cadence", "anchor", "evidence", "warn_days"}, kind)
        cadence = item.get("cadence")
        if cadence not in CADENCES and not EVERY.match(str(cadence or "")):
            errors.append(f"{where}: cadence must be weekly, monthly, quarterly, yearly or 'every N days'")
        if _date(item.get("anchor")) is None:
            errors.append(f"{where}: a recurring line needs an anchor (the first slot of the series)")
        ev = item.get("evidence")
        if not isinstance(ev, str) or not ev.strip():
            errors.append(f"{where}: evidence is required (a repo glob, check:<id> or none)")
        elif ev != "none" and not ev.startswith("check:"):
            if ev.startswith("/") or ".." in Path(ev).parts or "\\" in ev:
                errors.append(f"{where}: evidence must be a repo-relative glob")
            needs_warn = True
        elif ev.startswith("check:") and not CHECK_REF.match(ev):
            errors.append(f"{where}: evidence check id must look like check:monthly_review_recent")
    elif kind == "deadline":
        errors += _only(where, item, {"date", "window_from", "done", "evidence", "warn_days", "dates_from"}, kind)
        src = item.get("dates_from")
        if src is not None:
            if src not in DATES_FROM:
                errors.append(f"{where}: dates_from must be one of {', '.join(DATES_FROM)}")
            if item.get("date") is not None or item.get("window_from") is not None or item.get("done") is not None:
                errors.append(f"{where}: a dates_from line takes its dates from the register (no date, window, done)")
            needs_warn = True
        elif item.get("date") is None and item.get("window_from") is None:
            errors.append(f"{where}: a deadline needs a date, a window_from or a dates_from")
        if item.get("date") is not None:
            needs_warn = True
        d, w = _date(item.get("date")), _date(item.get("window_from"))
        if d and w and w > d:
            errors.append(f"{where}: window_from is after the date")
        ev = item.get("evidence")
        if ev is not None:
            if not isinstance(ev, str) or ev.startswith("/") or ".." in Path(ev).parts:
                errors.append(f"{where}: evidence must be a repo-relative path")
            elif not (root / ev).exists():
                errors.append(f"{where}: evidence {ev}: dead path")
    elif kind == "trigger":
        errors += _only(where, item, {"trigger", "trigger_date", "within_days", "done", "warn_days"}, kind)
        if not (isinstance(item.get("trigger"), str) and item["trigger"].strip()):
            errors.append(f"{where}: a trigger line needs the trigger event in words")
        if item.get("within_days") is None:
            errors.append(f"{where}: a trigger line needs within_days")
        needs_warn = True
    elif kind == "automated":
        errors += _only(where, item, {"cadence", "evidence"}, kind)
        if not (isinstance(item.get("cadence"), str) and item["cadence"].strip()):
            errors.append(f"{where}: an automated line needs its cadence in words")
        ev = item.get("evidence")
        if ev is not None and not (isinstance(ev, str) and CHECK_REF.match(ev)):
            errors.append(f"{where}: an automated line's evidence is a check:<id> (or none)")
    if needs_warn and item.get("warn_days") is None:
        errors.append(f"{where}: warn_days is required on a line that can be overdue (no default in code)")
    return errors


# ── evaluation ──────────────────────────────────────────────────────────────────────────────────────────────────────


def _due_state(due: date, today: date, warn: int) -> str:
    if due < today:
        return "overdue"
    if (due - today).days <= warn:
        return "due_soon"
    return "ok"


def evaluate_line(item: dict, today: date, root: Path = REPO_ROOT) -> Line:
    kind = item["kind"]
    warn = item.get("warn_days") or 0
    line = Line(id=item["id"], kind=kind, title=item["title"], owner=item["owner"], state="ok",
                note=item.get("note"), reminder=item.get("reminder"))
    ev = item.get("evidence")
    if isinstance(ev, str) and CHECK_REF.match(ev):
        line.check = CHECK_REF.match(ev).group(1)
    if kind == "automated":
        line.state = "automated"
        return line
    if kind == "recurring":
        cadence, anchor = item["cadence"], _date(item["anchor"])
        if ev == "none":
            line.state, line.due = "scheduled", next_slot(anchor, cadence, today)
            return line
        if line.check:
            line.state = "watched"
            return line
        dates = evidence_dates(root, ev)
        if dates:
            line.last = dates[-1]
            line.due = step(line.last, cadence)
        else:
            line.due = anchor
        line.state = _due_state(line.due, today, warn)
        return line
    if kind == "trigger":
        if _date(item.get("done")):
            line.state, line.last = "done", _date(item["done"])
            return line
        fired = _date(item.get("trigger_date"))
        if fired is None:
            line.state = "waiting"
            return line
        line.due = fired + timedelta(days=item["within_days"])
        line.state = _due_state(line.due, today, warn)
        return line
    # deadline
    if item.get("dates_from"):
        dates = sorted(register_dates(root, item["dates_from"]))
        if not dates:
            line.state, line.extra = "ok", "no dated rows"
            return line
        past = sum(1 for d in dates if d < today)
        soon = sum(1 for d in dates if today <= d and (d - today).days <= warn)
        line.due = dates[0]
        line.state = _due_state(dates[0], today, warn)
        line.extra = f"{past} past due, {soon} within {warn} days, of {len(dates)} dated rows"
        return line
    done = _date(item.get("done"))
    if done:
        line.state, line.last = "done", done
        line.due = _date(item.get("date"))
        return line
    due, window = _date(item.get("date")), _date(item.get("window_from"))
    line.due = due
    if window and today < window:
        line.state = "ok"
        if due is None:
            line.extra = f"opens {window.isoformat()}"
        return line
    if due is None:
        line.state = "open"
        line.extra = f"open since {window.isoformat()}" if window else None
        return line
    line.state = _due_state(due, today, warn)
    return line


def evaluate(doc: dict, today: date, root: Path = REPO_ROOT) -> list[Line]:
    return [evaluate_line(it, today, root) for it in doc.get("items", []) if isinstance(it, dict)]


def counts(lines: list[Line]) -> dict:
    out = {st: 0 for st in STATES}
    for ln in lines:
        out[ln.state] += 1
    return out


DRILL_LINE = {"id": "OC-999", "kind": "deadline", "title": "Drill: a deliberately past-due test line",
              "owner": "agent", "source": "AA-1184 drill (collector --drill-overdue)", "warn_days": 0,
              "reminder": "auto", "note": "Injected for one collector run to prove the check turns red."}


def evidence_detail(doc: dict, today: date, root: Path = REPO_ROOT, drill: bool = False) -> tuple[str, str, dict]:
    """(status, summary, detail) of the compliance check ``ops_calendar_overdue``.

    The detail fits the 8 KiB limit of compliance.evidence.detail: rows are compact arrays
    "id|kind|state|due|last|owner|title|check|extra|note" strings (:func:`_row`), and the notes of the lines that
    need no attention are dropped first, then their titles shortened, should the file ever grow past the budget."""
    errors = validate(doc, root)
    if errors:
        return "error", f"the calendar does not validate ({len(errors)} errors)", {"errors": len(errors)}
    if drill:
        doc = dict(doc, items=list(doc["items"]) + [dict(DRILL_LINE, date=(today - timedelta(days=1)).isoformat())])
    lines = evaluate(doc, today, root)
    c = counts(lines)
    rows = [_row(ln) for ln in lines]
    detail: dict[str, Any] = {"calendar_updated": doc.get("updated"), "today": today.isoformat(), "lines": len(lines),
                              "overdue": c["overdue"], "due_soon": c["due_soon"], "open": c["open"],
                              "counts": {k: v for k, v in c.items() if v}, "rows": rows, "drill": drill}
    _fit(detail)
    overdue = [ln.id for ln in lines if ln.state == "overdue"]
    if overdue:
        return "fail", f"{len(overdue)} overdue: {', '.join(overdue)}; {c['due_soon']} due soon", detail
    return "pass", f"0 overdue of {len(lines)} lines; {c['due_soon']} due soon, {c['open']} open", detail


DETAIL_BUDGET = 7600   # technical-constant: below the 8192-byte CHECK of compliance.evidence.detail (CIS 466)


def _size(detail: dict) -> int:
    import json   # noqa: PLC0415

    return len(json.dumps(detail).encode())


def _row(ln: Line) -> str:
    """One compact row "id|kind|state|due|last|owner|title|check|extra|note" (empty = none; kind and owner as codes:
    KIND_CODES, OWNER_CODES; the note only on a line that needs attention). A row is a string, not a JSON list, to fit
    every line under the 8 KiB detail limit; no calendar text may contain "|" (validate refuses it)."""
    cells = [ln.id, KIND_CODES[ln.kind], ln.state, ln.due.isoformat() if ln.due else "",
             ln.last.isoformat() if ln.last else "", OWNER_CODES[ln.owner], ln.title, ln.check or "", ln.extra or "",
             (ln.note or "") if ln.state in ATTENTION else ""]
    return "|".join(cells).rstrip("|")


ROW_FIELDS = ("id", "kind", "state", "due", "last", "owner", "title", "check", "extra", "note")


def parse_row(row: str) -> dict:
    """The inverse of :func:`_row` (the CIS reader does the same): a dict of ROW_FIELDS, empty cells as None."""
    cells = row.split("|", len(ROW_FIELDS) - 1)
    cells += [""] * (len(ROW_FIELDS) - len(cells))
    return {k: (v or None) for k, v in zip(ROW_FIELDS, cells)}


def _fit(detail: dict) -> None:
    """Keep the detail under the budget: shorten the titles of the lines that need no attention, then drop the
    automated lines (counted in ``counts``), then keep only the lines that need attention (``truncated``)."""
    rows = [parse_row(r) for r in detail["rows"]]

    def pack() -> None:
        detail["rows"] = ["|".join([r["id"], r["kind"], r["state"]] + [r[k] or "" for k in ROW_FIELDS[3:]]).rstrip("|")
                          for r in rows]

    for r in rows:
        if _size(detail) <= DETAIL_BUDGET:
            return
        if r["state"] not in ATTENTION and len(r["title"]) > 48:
            r["title"] = r["title"][:47] + "…"
            pack()
    if _size(detail) > DETAIL_BUDGET:
        rows = [r for r in rows if r["kind"] != KIND_CODES["automated"]]
        detail["automated_omitted"] = True
        pack()
    if _size(detail) > DETAIL_BUDGET:
        rows = [r for r in rows if r["state"] in ATTENTION]
        detail["truncated"] = True
        pack()


# ── rendering: the docs page table and the .ics feed ────────────────────────────────────────────────────────────────


def _cell(text: Any) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def when(item: dict) -> str:
    kind = item.get("kind")
    if kind == "recurring":
        return f"{item.get('cadence')} from {item.get('anchor')}"
    if kind == "automated":
        return str(item.get("cadence"))
    if kind == "trigger":
        base = f"{item.get('within_days')} days after: {item.get('trigger')}"
        return base + (f" (fired {item['trigger_date']})" if item.get("trigger_date") else "")
    if item.get("dates_from"):
        return f"dates read from the {REGISTER_NAMES[item['dates_from']]}"
    parts = []
    if item.get("window_from"):
        parts.append(f"from {item['window_from']}")
    if item.get("date"):
        parts.append(f"due {item['date']}")
    return ", ".join(parts)


def render(doc: dict) -> str:
    items = [it for it in doc.get("items", []) if isinstance(it, dict)]
    by_kind = {k: sum(1 for it in items if it.get("kind") == k) for k in KINDS}
    out = [f"Calendar version {doc.get('version')}, updated {doc.get('updated')}: **{len(items)} lines** "
           f"({', '.join(f'{v} {k}' for k, v in by_kind.items())}). Live states (overdue, due soon, open) are on the "
           "CIS Calendar tab and in `python3 tools/ops/ops_calendar.py status`; this table lists the lines only.",
           "", "| # | Kind | Duty | When | Owner | Evidence | Reminder | Done |", "|---|---|---|---|---|---|---|---|"]
    for it in items:
        evidence = it.get("evidence") or ("register" if it.get("dates_from") else "—")
        out.append("| " + " | ".join([
            _cell(it.get("id")), _cell(it.get("kind")), _cell(it.get("title", "")), _cell(when(it)),
            _cell(it.get("owner", "")), f"`{_cell(evidence)}`" if evidence not in ("—",) else "—",
            _cell(it.get("reminder", "")), _cell(it.get("done") or "—"),
        ]) + " |")
    return "\n".join(out)


def splice(page_text: str, block: str) -> str:
    lines = page_text.split("\n")
    begins = [i for i, line in enumerate(lines) if BEGIN_RE.match(line)]
    ends = [i for i, line in enumerate(lines) if END_RE.match(line)]
    if len(begins) != 1 or len(ends) != 1 or ends[0] < begins[0]:
        raise CalendarError(f"{PAGE}: needs exactly one ops-calendar:begin marker followed by one ops-calendar:end")
    return "\n".join(lines[:begins[0]] + [BEGIN, "", block, "", END] + lines[ends[0] + 1:])


_RRULE = {"weekly": "FREQ=WEEKLY", "monthly": "FREQ=MONTHLY", "quarterly": "FREQ=MONTHLY;INTERVAL=3",
          "yearly": "FREQ=YEARLY"}


def _ics_escape(text: str) -> str:
    return (text.replace("\\", "\\\\").replace(";", "\\;").replace(",", "\\,").replace("\n", "\\n"))


def _fold(line: str) -> list[str]:
    """RFC 5545 3.1: lines over 75 octets are folded (CRLF + one space), never inside a UTF-8 sequence."""
    out, cur = [], b""
    for ch in line:
        b = ch.encode("utf-8")
        if len(cur) + len(b) > (75 if not out else 74):
            out.append(cur.decode("utf-8"))
            cur = b""
        cur += b
    out.append(cur.decode("utf-8"))
    return [out[0]] + [" " + s for s in out[1:]]


def _event(uid: str, stamp: str, day: date, summary: str, description: str, rrule: Optional[str] = None,
           alarm_days: Optional[int] = None) -> list[str]:
    ev = ["BEGIN:VEVENT", f"UID:{uid}", f"DTSTAMP:{stamp}", f"DTSTART;VALUE=DATE:{day.strftime('%Y%m%d')}",
          f"DTEND;VALUE=DATE:{(day + timedelta(days=1)).strftime('%Y%m%d')}",
          f"SUMMARY:{_ics_escape(summary)}", f"DESCRIPTION:{_ics_escape(description)}", "TRANSP:TRANSPARENT"]
    if rrule:
        ev.append(f"RRULE:{rrule}")
    if alarm_days:
        ev += ["BEGIN:VALARM", "ACTION:DISPLAY", f"DESCRIPTION:{_ics_escape(summary)}",
               f"TRIGGER:-P{alarm_days}D", "END:VALARM"]
    ev.append("END:VEVENT")
    return ev


def _rrule(cadence: str) -> str:
    if cadence in _RRULE:
        return _RRULE[cadence]
    return f"FREQ=DAILY;INTERVAL={EVERY.match(cadence).group(1)}"


def ics(doc: dict) -> str:
    """The phone feed: a pure function of calendar.yaml (no today, no register, DTSTAMP = the calendar's `updated`),
    one all-day event per dated line and a repeating event per recurring line (from its anchor).

    A ``dates_from`` line gets no event: its dates live in another register (secrets register, go-live checklist,
    vulnerability exceptions), and copying them into the committed feed would make it stale on every edit of that
    register, turning the freshness guard red on unrelated pull requests. Their live state is on the CIS Calendar tab
    and in ``status``."""
    stamp = _date(doc.get("updated")).strftime("%Y%m%dT000000Z")
    out = ["BEGIN:VCALENDAR", "VERSION:2.0", "PRODID:-//AA Ecosystem//Ops calendar//EN", "CALSCALE:GREGORIAN",
           "METHOD:PUBLISH", "X-WR-CALNAME:AA ops calendar", "X-WR-TIMEZONE:UTC"]
    for it in (i for i in doc.get("items", []) if isinstance(i, dict)):
        iid, kind, title = it["id"], it["kind"], it["title"]
        desc = f"{iid} ({kind}) · owner: {it['owner']} · source: {it['source']}"
        if it.get("note"):
            desc += f"\n{it['note']}"
        warn = it.get("warn_days") or None
        uid = f"{iid.lower()}@ops-calendar.aa-ecosys"
        if kind == "recurring":
            ev = it.get("evidence")
            desc += f"\nEvidence: {ev}"
            out += _event(uid, stamp, _date(it["anchor"]), f"{iid} {title}", desc, _rrule(it["cadence"]), warn)
        elif kind == "deadline" and it.get("dates_from"):
            continue   # dates read from a register: live state only (see the docstring)
        elif kind == "deadline":
            day = _date(it.get("date")) or _date(it.get("window_from"))
            prefix = "(done) " if it.get("done") else ("opens: " if not it.get("date") else "")
            out += _event(uid, stamp, day, f"{prefix}{iid} {title}", desc, None, None if it.get("done") else warn)
        elif kind == "trigger" and it.get("trigger_date"):
            day = _date(it["trigger_date"]) + timedelta(days=it["within_days"])
            out += _event(uid, stamp, day, f"{iid} {title}", desc + f"\nTrigger: {it['trigger']}", None, warn)
    out.append("END:VCALENDAR")
    return "".join(f"{seg}\r\n" for line in out for seg in _fold(line))


# ── CLI ─────────────────────────────────────────────────────────────────────────────────────────────────────────────


def _today(value: Optional[str]) -> date:
    return date.fromisoformat(value) if value else datetime.now(timezone.utc).date()


def cmd_check(args: argparse.Namespace) -> int:
    root, today = Path(args.root), _today(args.today)
    errors: list[str] = []
    overdue: list[Line] = []
    soon: list[Line] = []
    lines: list[Line] = []
    try:
        doc = load(root, args.calendar)
        errors = validate(doc, root)
        if not errors:
            lines = evaluate(doc, today, root)
            overdue = [ln for ln in lines if ln.state == "overdue"]
            soon = [ln for ln in lines if ln.state == "due_soon"]
            page = (root / PAGE).read_text(encoding="utf-8")
            if splice(page, render(doc)) != page:
                errors.append(f"{PAGE}: the table is stale; run python3 tools/ops/ops_calendar.py render --write")
            feed = root / ICS
            if not feed.exists() or feed.read_bytes() != ics(doc).encode("utf-8"):
                errors.append(f"{ICS}: stale; run python3 tools/ops/ops_calendar.py ics --write")
    except (CalendarError, GateError, OSError) as exc:
        errors.append(str(exc))
    level = "warning" if args.warn_overdue else "error"
    for ln in overdue:
        print(f"::{level} title=Ops calendar::{ln.id} overdue since {ln.due} (owner: {ln.owner}): {ln.title}"
              + (f" [{ln.extra}]" if ln.extra else ""))
    for ln in soon:
        print(f"::warning title=Ops calendar::{ln.id} due {ln.due} (owner: {ln.owner}): {ln.title}")
    for e in errors:
        print(f"::error title=Ops calendar::{e}")
    failed = bool(errors) or (bool(overdue) and not args.warn_overdue)
    c = counts(lines) if lines else {}
    summary = (f"ops calendar {'FAIL' if failed else 'OK'} on {today.isoformat()}: {len(lines)} lines, "
               f"{c.get('overdue', 0)} overdue, {c.get('due_soon', 0)} due soon, {c.get('open', 0)} open, "
               f"{len(errors)} error(s)")
    print(summary)
    if args.summary:
        with open(args.summary, "a", encoding="utf-8") as fh:
            fh.write(f"## Ops calendar\n\n{summary}\n\n")
            for ln in overdue:
                fh.write(f"- overdue: {ln.id} since {ln.due} ({ln.owner}): {ln.title}\n")
            for ln in soon:
                fh.write(f"- due soon: {ln.id} on {ln.due} ({ln.owner}): {ln.title}\n")
            for e in errors:
                fh.write(f"- error: {e}\n")
    return 1 if failed else 0


def cmd_status(args: argparse.Namespace) -> int:
    root, today = Path(args.root), _today(args.today)
    doc = load(root, args.calendar)
    errors = validate(doc, root)
    if errors:
        for e in errors:
            print(f"error: {e}")
        return 2
    lines = evaluate(doc, today, root)
    order = {st: i for i, st in enumerate(STATES)}
    shown = [ln for ln in lines if args.all or ln.state in ATTENTION or
             (ln.state in ("ok", "scheduled") and ln.due and (ln.due - today).days <= args.days)]
    shown.sort(key=lambda ln: (order[ln.state], ln.due or date.max, ln.id))
    c = counts(lines)
    print(f"ops calendar {today.isoformat()}: {c['overdue']} overdue, {c['due_soon']} due soon, {c['open']} open, "
          f"{len(lines)} lines")
    for ln in shown:
        print(f"{ln.state.upper():<10} {ln.id}  {str(ln.due or ''):<10}  {ln.owner:<14} {ln.title}"
              + (f"  [{ln.extra}]" if ln.extra else ""))
    return 1 if c["overdue"] else 0


def _write(root: Path, rel: str, new: str) -> None:
    path = root / rel
    old = path.read_bytes() if path.exists() else None
    data = new.encode("utf-8")
    if old == data:
        print(f"{rel} already up to date")
        return
    path.write_bytes(data)
    print(f"rewrote {rel}")


def cmd_render(args: argparse.Namespace) -> int:
    root = Path(args.root)
    block = render(load(root, args.calendar))
    if not args.write:
        print(block)
        return 0
    page = (root / PAGE).read_text(encoding="utf-8")
    _write(root, PAGE, splice(page, block))
    return 0


def cmd_ics(args: argparse.Namespace) -> int:
    root = Path(args.root)
    feed = ics(load(root, args.calendar))
    if not args.write:
        sys.stdout.write(feed)
        return 0
    _write(root, ICS, feed)
    return 0


def main(argv: Optional[list[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("--root", default=str(REPO_ROOT), help="repo root (default: this repo)")
    ap.add_argument("--calendar", default=CALENDAR)
    sub = ap.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("check", help="validate the calendar, the page and the .ics; fail on an overdue line")
    c.add_argument("--today", help="ISO date to check against (default: today, UTC)")
    c.add_argument("--summary", help="append a Markdown summary to this file (GITHUB_STEP_SUMMARY)")
    c.add_argument("--warn-overdue", action="store_true", help="report overdue lines as warnings (pull requests)")
    s = sub.add_parser("status", help="the lines that need attention (session start)")
    s.add_argument("--today")
    s.add_argument("--days", type=int, default=7, help="also list ok lines due within this many days")
    s.add_argument("--all", action="store_true")
    r = sub.add_parser("render", help="print or rewrite the table of the docs page")
    r.add_argument("--write", action="store_true")
    i = sub.add_parser("ics", help="print or rewrite the .ics feed")
    i.add_argument("--write", action="store_true")
    args = ap.parse_args(argv)
    return {"check": cmd_check, "status": cmd_status, "render": cmd_render, "ics": cmd_ics}[args.cmd](args)


if __name__ == "__main__":
    sys.exit(main())
