#!/usr/bin/env python3
"""AA-1184 (S297) — the ops calendar: one file for every dated and recurring ops duty, a guard that turns a passed due
date red, the phone feed and the table of the docs page.

The calendar is docs/ops/calendar.yaml (the field list is in its header). It is read with the same YAML subset parser
as the go-live gate (tools/ops/golive_gate.py ``parse_yaml``: standard library, a construct outside the subset is an
error with its line number). Three lines read their dates from other registers instead of copying them:
``secrets-register`` (the rotation blocks of docs/security/secrets-register.yaml, via
tools/security/secrets_register.py, which needs PyYAML), ``go-live-checklist`` (the due dates of the open go-live gate
lines) and ``vuln-exceptions`` (docs/security/vuln-exceptions.toml).

Every line gets a state for a given day:

  overdue    a due date has passed and the duty is not done (red; the only state that fails the check)
  due_soon   the due date is within the line's warn_days (amber)
  open       a "not before" window has opened and the duty has no due date (amber, never overdue)
  ok         the next due date is further away, or a window not yet open
  done       a deadline or trigger with a ``done`` date
  scheduled  a reminder-only recurring line (evidence: none): the next slot of its series
  watched    a recurring line graded by a compliance check (evidence: check:<id>); CIS shows that check's state
  waiting    a trigger whose event has not happened (no trigger_date)
  automated  a job or workflow that runs by itself (listed, never due)

Commands:

    python3 tools/ops/ops_calendar.py check [--today D] [--warn-overdue]   validate, page + .ics up to date, overdue
    python3 tools/ops/ops_calendar.py status [--today D] [--all]           the lines that need attention (session start)
    python3 tools/ops/ops_calendar.py render --write                       the table in docs/ops/calendar.md
    python3 tools/ops/ops_calendar.py ics --write                          docs/ops/calendar.ics (deterministic, YAML only)

``check`` exits 1 on a validation error, a stale page or .ics, and (unless ``--warn-overdue``, the pull-request mode)
on an overdue line. The daily compliance collector publishes the same evaluation as the check ``ops_calendar_overdue``
(:func:`evidence_detail`), which CIS Platform > Compliance readiness shows on its Calendar tab.
"""
