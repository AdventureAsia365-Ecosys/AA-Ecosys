"""UAT / intro packaging (skill aa-uat-video): pack one video into a zip that can be sent as is: one MP4 per language, the narration audio of each
language (MP3), the subtitles (SRT + VTT), the narration script (Markdown, from the subtitles or the scene script) and
a README in Vietnamese and English. No internal ids, no run logs, no result.json.

    python3 package.py uat    <SCENARIO>_<yyyymmdd>_v<n> "<title>"     # out/<stem>.mp4 with an eng + vie audio track
    python3 package.py intro  TripPlanner-intro <yyyymmdd> "<title>"   # TripPlanner-intro-{EN,VI}_<date>.mp4
"""
import json
import os
import re
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "out"
PKG = OUT / "packages"
VI_VOICE = os.environ.get("UAT_VI_VOICE", "Thục Đoan")
VI_LABEL = ("VieNeu-TTS v3 Turbo — giọng nữ miền Nam (Apache-2.0)" if VI_VOICE == "Thục Đoan"
            else "VieNeu-TTS v3 Turbo (Apache-2.0)")
LANG = {"en": ("English", "eng", "Kokoro — giọng nữ (Apache-2.0)"),
        "vi": ("Tiếng Việt", "vie", VI_LABEL)}


def run(*cmd):
    subprocess.run(cmd, check=True, capture_output=True)


def duration(mp4: Path) -> float:
    r = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(mp4)],
                       check=True, capture_output=True, text=True)
    return float(r.stdout.strip())


def audio_streams(mp4: Path) -> dict:
    r = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "a", "-show_entries",
                        "stream=index:stream_tags=language", "-of", "json", str(mp4)],
                       check=True, capture_output=True, text=True)
    out = {}
    for i, s in enumerate(json.loads(r.stdout).get("streams", [])):
        out[(s.get("tags") or {}).get("language", f"a{i}")] = i
    return out


def srt_to_script(srt: Path, title: str, lang: str) -> str:
    blocks = [b for b in re.split(r"\n\s*\n", srt.read_text(encoding="utf-8").strip()) if b.strip()]
    lines = [f"# {title} — {LANG[lang][0]}", ""]
    for b in blocks:
        rows = b.strip().splitlines()
        if len(rows) < 3:
            continue
        start = rows[1].split(" --> ")[0].split(",")[0]
        lines.append(f"- **{start}** {' '.join(rows[2:]).strip()}")
    return "\n".join(lines) + "\n"


def readme(title: str, items: list) -> str:
    vi = [f"{title}", "", "Gói này gồm:"]
    en = ["", "-" * 60, "", f"{title}", "", "This package contains:"]
    for it in items:
        name, lang, secs = it["video"], it["lang"], it["secs"]
        mm, ss = divmod(round(secs), 60)
        vi.append(f"- video/{name}: video {LANG[lang][0]}, dài {mm} phút {ss:02d} giây, có phụ đề.")
        en.append(f"- video/{name}: {LANG[lang][0]} video, {mm} min {ss:02d} s, with subtitles.")
    vi += ["- audio/: giọng đọc riêng của từng ngôn ngữ (MP3).",
           "- subtitles/: phụ đề SRT và VTT (mở kèm video trong VLC hoặc trình phát bất kỳ).",
           "- script/: lời đọc theo thời gian, để đọc hoặc sửa.",
           "", "Cách xem: mở file MP4 bằng trình phát video có sẵn trên máy hoặc điện thoại.",
           "Giọng đọc tạo bằng phần mềm chạy trên máy (miễn phí, không gửi dữ liệu ra ngoài):"]
    en += ["- audio/: the narration of each language on its own (MP3).",
           "- subtitles/: SRT and VTT subtitles (load them in VLC or any player).",
           "- script/: the timed narration text, to read or edit.",
           "", "To watch: open the MP4 in any video player on a computer or phone.",
           "The voices are generated by software run locally (free, no data sent out):"]
    for lang in sorted({it["lang"] for it in items}):
        vi.append(f"  {LANG[lang][0]}: {LANG[lang][2]}")
        en.append(f"  {LANG[lang][0]}: {LANG[lang][2]}")
    vi += ["", "Dữ liệu trong video là dữ liệu môi trường thử nghiệm (Dev), không phải dữ liệu khách thật."]
    en += ["", "The data shown is from the test (Dev) environment, not real customer data."]
    return "\n".join(vi + en) + "\n"


def pack(name: str, title: str, items: list, extra_scripts: list) -> Path:
    stage = PKG / name
    shutil.rmtree(stage, ignore_errors=True)
    for d in ("video", "audio", "subtitles", "script"):
        (stage / d).mkdir(parents=True)
    for it in items:
        shutil.copy2(it["mp4"], stage / "video" / it["video"])
        run("ffmpeg", "-y", "-hide_banner", "-loglevel", "error", "-i", str(it["mp4"]), "-map", f"0:a:{it['track']}",
            "-vn", "-c:a", "libmp3lame", "-q:a", "2", str(stage / "audio" / f"{Path(it['video']).stem}.mp3"))
        for ext in ("srt", "vtt"):
            if it.get(ext) and Path(it[ext]).exists():
                shutil.copy2(it[ext], stage / "subtitles" / f"{Path(it['video']).stem}.{ext}")
        if it.get("srt") and Path(it["srt"]).exists():
            (stage / "script" / f"{Path(it['video']).stem}.md").write_text(
                srt_to_script(Path(it["srt"]), title, it["lang"]), encoding="utf-8")
    for src in extra_scripts:
        if Path(src).exists():
            shutil.copy2(src, stage / "script" / Path(src).name)
    (stage / "README.txt").write_text(readme(title, items), encoding="utf-8")
    zp = PKG / f"{name}.zip"
    if zp.exists():
        zp.unlink()
    with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(stage.rglob("*")):
            if f.is_file():
                z.write(f, f"{name}/{f.relative_to(stage)}")
    return zp


def uat(stem: str, title: str) -> Path:
    mp4 = OUT / f"{stem}.mp4"
    tracks = audio_streams(mp4)
    secs = duration(mp4)
    items = []
    for lang, code in (("en", "eng"), ("vi", "vie")):
        if code not in tracks:
            continue
        one = PKG / f".{stem}.{lang}.mp4"
        PKG.mkdir(parents=True, exist_ok=True)
        run("ffmpeg", "-y", "-hide_banner", "-loglevel", "error", "-i", str(mp4), "-map", "0:v:0", "-map",
            f"0:a:{tracks[code]}", "-c", "copy", str(one))
        items.append({"mp4": one, "video": f"{stem}_{lang.upper()}.mp4", "lang": lang, "track": 0, "secs": secs,
                      "srt": OUT / f"{stem}.{lang}.srt", "vtt": OUT / f"{stem}.{lang}.vtt"})
    zp = pack(stem, title, items, [])
    for it in items:
        Path(it["mp4"]).unlink(missing_ok=True)
    return zp


def intro(base: str, date: str, title: str) -> Path:
    d = OUT / "intro"
    items = []
    for lang in ("en", "vi"):
        mp4 = d / f"{base}-{lang.upper()}_{date}.mp4"
        if not mp4.exists():
            continue
        items.append({"mp4": mp4, "video": mp4.name, "lang": lang, "track": 0, "secs": duration(mp4),
                      "srt": d / f"{base}-{lang.upper()}_{date}.srt", "vtt": d / f"{base}-{lang.upper()}_{date}.vtt"})
    extras = sorted(str(p) for p in d.glob("*.md"))
    return pack(f"{base}_{date}", title, items, extras)


if __name__ == "__main__":
    kind = sys.argv[1]
    zp = uat(sys.argv[2], sys.argv[3]) if kind in ("uat", "pilot") else intro(sys.argv[2], sys.argv[3], sys.argv[4])
    print(zp, zp.stat().st_size)
