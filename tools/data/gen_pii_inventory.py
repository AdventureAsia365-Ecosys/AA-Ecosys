#!/usr/bin/env python3
"""Column inventory of the RoPA from the DM-6.1 column tags (AA-877).

Reads the generated schema reference (docs/architecture/db-schema-reference.md, written by AA-CIS-Infra
db/gen_schema_reference.py from the live catalog), section *Personal and confidential data tags (DM-6.1)*, table
*Tagged columns*, for every schema. Writes a generated block "Column inventory (from pii tags)" between markers into
section (a) of the compliance register (docs/legal/register.md, SEC-04), and compares the tags with the RoPA table of
that section:

  * a tagged column (pii:* or conf:credential) that no RoPA row names = a new processing line (fix the RoPA);
  * a column of booking.* / tripplanner.* that a RoPA row names, that exists in the reference and has no tag =
    a tagging gap (fix the owner's migration, or accept it: consent flags and pseudonymous refs are untagged on
    purpose, data standards DM-6.1).

conf:commercial is business data, not personal data: it is listed in the reference but not in the inventory.

Usage (from the repo root):
  python3 tools/data/gen_pii_inventory.py            # rewrite the block in docs/legal/register.md
  python3 tools/data/gen_pii_inventory.py --check    # exit 1 when the block is stale or a tagged column has no row
  python3 tools/data/gen_pii_inventory.py --check --strict   # ... or when a named booking/tripplanner column has no tag

Standard library only. Output is deterministic for a given reference and register.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REFERENCE = ROOT / "docs" / "architecture" / "db-schema-reference.md"
REGISTER = ROOT / "docs" / "legal" / "register.md"

START = "<!-- pii-inventory:start (generated by tools/data/gen_pii_inventory.py; do not edit by hand) -->"
END = "<!-- pii-inventory:end -->"
SECTION_HEADING = "## Personal and confidential data tags (DM-6.1)"
TAGGED_HEADING = "### Tagged columns"
ROPA_HEADING = "## (a) Records of processing (RoPA)"
INSERT_BEFORE = ("### How to regenerate this table", "## (b)")
GAP_SCHEMAS = ("booking", "tripplanner")

VERIFIED_RE = re.compile(r"^\*\*Verified:\*\* (\S+ \S+ UTC)", re.M)
RELATION_RE = re.compile(r"^### `([a-z_][a-z0-9_]*)\.([a-z_][a-z0-9_]*)`", re.M)
TAGGED_ROW_RE = re.compile(r"^\| `([^`]+)` \| `([^`]+)` \| `([^`]+)` \| `([^`]+)` \| (.*) \|$")
CODE_RE = re.compile(r"`([^`]+)`")
REL_COLS_RE = re.compile(r"`([a-z_][a-z0-9_]*)\.([a-z_][a-z0-9_]*)`\s*\(")
TRIPLE_RE = re.compile(r"^([a-z_][a-z0-9_]*)\.([a-z_][a-z0-9_]*)\.([a-z_][a-z0-9_]*)$")
IDENT_RE = re.compile(r"^[a-z_][a-z0-9_]*$")


class InventoryError(Exception):
    pass


def _section(text: str, heading: str) -> str:
    """Text from `heading` to the next heading of the same or a higher level."""
    level = len(heading) - len(heading.lstrip("#"))
    start = text.find(heading + "\n")
    if start < 0:
        raise InventoryError(f"heading not found: {heading!r}")
    body_start = start + len(heading) + 1
    stop = re.compile(r"^#{1,%d} " % level, re.M).search(text, body_start)
    return text[body_start:stop.start() if stop else len(text)]


def parse_reference(text: str) -> dict:
    """{'verified': str|None, 'tagged': [{schema, relation, column, tag, also}], 'columns': {(schema, relation): set}}"""
    m = VERIFIED_RE.search(text)
    tagged = []
    for line in _section(_section(text, SECTION_HEADING), TAGGED_HEADING).splitlines():
        row = TAGGED_ROW_RE.match(line.strip())
        if row:
            schema, relation, column, tag, also = row.groups()
            tagged.append({"schema": schema, "relation": relation, "column": column, "tag": tag,
                           "also": CODE_RE.findall(also)})
    columns: dict = {}
    for rel in RELATION_RE.finditer(text):
        block = re.search(r"```\n(.*?)\n```", text[rel.end():], re.S)
        if block:
            columns[(rel.group(1), rel.group(2))] = {ln.split(" ", 1)[0] for ln in block.group(1).splitlines() if ln}
    return {"verified": m.group(1) if m else None, "tagged": tagged, "columns": columns}


def _paren_body(text: str, open_at: int) -> str:
    """Text inside the parenthesis that opens at `open_at`, nested parentheses included."""
    depth = 0
    for i in range(open_at, len(text)):
        if text[i] == "(":
            depth += 1
        elif text[i] == ")":
            depth -= 1
            if depth == 0:
                return text[open_at + 1:i]
    return text[open_at + 1:]


def named_columns(cell: str) -> set:
    """(schema, relation, column) named in a RoPA 'Tables and columns' cell: `s.r.c`, and `s.r` (`c1`, `c2`, …)."""
    out = set()
    for code in CODE_RE.findall(cell):
        t = TRIPLE_RE.match(code)
        if t:
            out.add(t.groups())
    for m in REL_COLS_RE.finditer(cell):
        schema, relation = m.groups()
        for code in CODE_RE.findall(_paren_body(cell, m.end() - 1)):
            if IDENT_RE.match(code):
                out.add((schema, relation, code))
    return out


def parse_ropa(register: str) -> dict:
    """{row number: set of (schema, relation, column)} from the RoPA table of section (a)."""
    section = _section(register, ROPA_HEADING)
    header, rows = None, {}
    for line in section.splitlines():
        if not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if header is None:
            header = cells
            continue
        if set(line.replace("|", "").strip()) <= {"-", " ", ":"}:
            continue
        if "#" not in header or "Tables and columns" not in " ".join(header):
            break
        number = cells[header.index("#")]
        col = next(i for i, h in enumerate(header) if h.startswith("Tables and columns"))
        if number.isdigit():
            rows[int(number)] = named_columns(cells[col])
    if not rows:
        raise InventoryError("no RoPA rows found in section (a) (expected a table with '#' and 'Tables and columns')")
    return rows


def inventory(ref: dict, ropa: dict) -> dict:
    """Inventory rows (personal data and credentials) with the RoPA rows that name them, plus the two findings."""
    rows, new_lines = [], []
    tagged_keys = set()
    for t in ref["tagged"]:
        key = (t["schema"], t["relation"], t["column"])
        tagged_keys.add(key)
        if t["tag"] == "conf:commercial":
            continue
        in_rows = sorted(n for n, cols in ropa.items() if key in cols)
        rows.append({**t, "ropa": in_rows})
        if not in_rows:
            new_lines.append(".".join(key))
    gaps = sorted(".".join(key) for cols in ropa.values() for key in cols
                  if key[0] in GAP_SCHEMAS and key not in tagged_keys
                  and key[2] in ref["columns"].get((key[0], key[1]), set()))
    return {"rows": rows, "new_lines": new_lines, "gaps": sorted(set(gaps))}


def render_block(ref: dict, inv: dict) -> str:
    pii = sum(1 for r in inv["rows"] if r["tag"].startswith("pii:"))
    cred = len(inv["rows"]) - pii
    lines = [
        START,
        "",
        "### Column inventory (from pii tags)",
        "",
        "Generated from the *Personal and confidential data tags (DM-6.1)* section of "
        "[`db-schema-reference.md`](../architecture/db-schema-reference.md)"
        + (f" (Verified {ref['verified']})" if ref.get("verified") else "")
        + f": {pii} personal-data column(s) and {cred} credential column(s) over every schema. `conf:commercial` "
        "columns are business data and are left out. \"RoPA row\" is the row of the table above that names the "
        "column; **none** marks a new processing line.",
        "",
        "| Schema | Relation | Column | Tag | Also | RoPA row |",
        "|---|---|---|---|---|---|",
    ]
    for r in inv["rows"]:
        also = ", ".join(f"`{a}`" for a in r["also"])
        where = ", ".join(str(n) for n in r["ropa"]) or "**none**"
        lines.append(f"| `{r['schema']}` | `{r['relation']}` | `{r['column']}` | `{r['tag']}` | {also} | {where} |")
    if not inv["rows"]:
        lines.append("| none | | | | | |")
    lines += ["", END]
    return "\n".join(lines)


def write_block(register: str, block: str) -> str:
    """The register with the generated block replaced, or inserted at the end of section (a) the first time."""
    if START in register:
        a, rest = register.split(START, 1)
        if END not in rest:
            raise InventoryError("start marker without end marker in the register")
        return a + block + rest.split(END, 1)[1]
    section_at = register.find(ROPA_HEADING + "\n")
    if section_at < 0:
        raise InventoryError(f"heading not found: {ROPA_HEADING!r}")
    for heading in INSERT_BEFORE:
        at = register.find("\n" + heading, section_at)
        if at >= 0:
            return register[:at + 1] + block + "\n\n" + register[at + 1:]
    raise InventoryError("no place for the block: neither of " + ", ".join(INSERT_BEFORE) + " follows section (a)")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--reference", type=Path, default=REFERENCE)
    ap.add_argument("--register", type=Path, default=REGISTER)
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 on a stale block or a new line")
    ap.add_argument("--strict", action="store_true", help="with --check, also exit 1 on a tagging gap")
    args = ap.parse_args(argv)
    try:
        ref = parse_reference(args.reference.read_text(encoding="utf-8"))
        register = args.register.read_text(encoding="utf-8")
        inv = inventory(ref, parse_ropa(register))
        updated = write_block(register, render_block(ref, inv))
    except InventoryError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    print(f"tagged columns: {len(ref['tagged'])}; inventory rows: {len(inv['rows'])}; "
          f"new processing lines: {len(inv['new_lines'])}; tagging gaps: {len(inv['gaps'])}")
    for key in inv["new_lines"]:
        print(f"  new processing line (tagged, in no RoPA row): {key}")
    for key in inv["gaps"]:
        print(f"  tagging gap (named in a RoPA row, no tag): {key}")
    if args.check:
        stale = updated != register
        if stale:
            print("  the generated block is stale: run tools/data/gen_pii_inventory.py")
        return 1 if stale or inv["new_lines"] or (args.strict and inv["gaps"]) else 0
    if updated != register:
        args.register.write_text(updated, encoding="utf-8")
        print(f"wrote {args.register}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
