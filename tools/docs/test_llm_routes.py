class RenderTest(unittest.TestCase):
    def test_routes_sorted_with_app_chain_and_shadow(self) -> None:
        page = g.render(SNAP)
        rows = [ln for ln in page.splitlines() if ln.startswith("| `")]
        stages = [r.split("|")[1].strip() for r in rows[:3]]
        self.assertEqual(stages, ["`a3_atomize`", "`t9_write`", "`tp_compose`"])
        self.assertIn("| `t9_write` | CIS | writer | yes | `zz-writer` | `zz-writer-b` | - | acc3 | 2026-10-20 |", page)
        self.assertIn("| `a3_atomize` | CIS | validate | yes | `zz-judge` | - | `zz-writer` (10 %) | acc3 |", page)
        self.assertIn("| `tp_compose` | TripPlanner | writer | no | `haiku` |", page)

    def test_models_prices_usage_and_blocked_reason(self) -> None:
        page = g.render(SNAP)
        self.assertIn("| 3 / 15 | 0.3 / - | 8192 | `a3_atomize`, `t9_write` |", page)
        self.assertIn("no: not offered \\| here", page)
        self.assertIn("Route keys with no catalog row (legacy keys the gateway resolves in code): `haiku`.", page)

    def test_render_is_deterministic_and_order_free(self) -> None:
        shuffled = dict(SNAP, routes=list(reversed(SNAP["routes"])), models=list(reversed(SNAP["models"])))
        self.assertEqual(g.render(SNAP), g.render(shuffled))
        self.assertEqual(g.snapshot_text(SNAP), g.snapshot_text(shuffled))

    def test_generated_header(self) -> None:
        page = g.render(SNAP)
        self.assertIn("generated: true\ngenerator: tools/docs/gen_llm_routes.py\n", page)
        self.assertIn("<!-- GENERATED by tools/docs/gen_llm_routes.py from", page)
        self.assertIn(f"docs-fingerprint: {g.fingerprint(SNAP)}", page)

    def test_empty_snapshot_says_so(self) -> None:
        page = g.render({"schema": g.SCHEMA, "routes": [], "models": []})
        self.assertIn("## No snapshot yet", page)

    def test_wrong_schema_is_refused(self) -> None:
        with self.assertRaises(ValueError):
            g.render({"schema": "other", "routes": []})


class SafetyTest(unittest.TestCase):
    def test_redact_removes_arns_and_account_ids(self) -> None:
        dirty = {"x": "arn:aws:bedrock:us-west-1:" + "1" * 12 + ":inference-profile/abc", "y": ["acct " + "2" * 12],
                 "z": "1234567890123 is thirteen digits"}
        clean = g.redact(dirty)
        self.assertEqual(clean["x"], "[redacted]")
        self.assertEqual(clean["y"], ["acct [redacted]"])
        self.assertEqual(clean["z"], dirty["z"])
        self.assertEqual(g.find_ids(clean), [])
        self.assertEqual(len(g.find_ids(dirty)), 2)

    def test_extract_from_a_noisy_exec_log(self) -> None:
        log = ("Starting session with SessionId: x\r\n" + g.BEGIN + "\r\n" + json.dumps(SNAP) + "\r\n" + g.END
               + "\r\nExiting session\r\n")
        self.assertEqual(g.extract(log), g.normalise(SNAP))
        with self.assertRaises(ValueError):
            g.extract("no markers here")

    def test_check_flags_a_hand_edit_and_an_unnormalised_snapshot(self) -> None:
        with tempfile.TemporaryDirectory() as d:
            snap, page = Path(d) / "s.json", Path(d) / "p.md"
            snap.write_text(g.snapshot_text(SNAP), encoding="utf-8")
            page.write_text(g.render(SNAP), encoding="utf-8")
            self.assertEqual(g.check(snap, page), [])
            page.write_text(g.render(SNAP).replace("zz-judge", "zz-other", 1), encoding="utf-8")
            self.assertTrue(any("page differs" in p for p in g.check(snap, page)))
            snap.write_text(json.dumps(SNAP), encoding="utf-8")
            self.assertTrue(any("normalised" in p for p in g.check(snap, page)))


