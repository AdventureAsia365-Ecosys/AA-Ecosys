@unittest.skipIf(check_frontmatter is None, "needs PyYAML and jsonschema (tools/docs/requirements.txt)")
class FrontMatterTest(TempRepo):
    def setUp(self) -> None:
        super().setUp()
        (self.root / "docs/templates").mkdir(parents=True)
        shutil.copy(SCHEMA, self.root / "docs/templates/frontmatter.schema.json")

    def errors(self) -> list[str]:
        pages, parse_errors = check_frontmatter.load_pages(self.root)
        return [f.message for f in parse_errors + check_frontmatter.validate(self.root, pages)]

    def test_root_context_page_is_checked(self) -> None:
        self.write("CONTEXT.md", GOOD_FM.replace("type: how-to", "type: repo-context"))
        self.write("README.md", "---\nnot: checked\n---\n")
        msgs = self.errors()
        self.assertEqual(len(msgs), 1)
        self.assertIn("'repo-context' is not one of", msgs[0])

    def test_valid_page_passes(self) -> None:
        self.write("docs/ops/rollback.md", GOOD_FM)
        self.write("docs/sessions/2026-01-01-x.md", "# No front-matter in journals\n")
        self.assertEqual(self.errors(), [])

    def test_schema_violations_fail(self) -> None:
        self.write("docs/a.md", GOOD_FM.replace("last_reviewed", "last-reviewed"))
        self.write("docs/b.md", GOOD_FM.replace("status: active", "status: superseded").replace("OPS-02", "OPS-03"))
        self.write("docs/c.md", GOOD_FM.replace("id: OPS-02", "id: ops-2"))
        self.write("docs/d.md", "---\nid: [unclosed\n---\n")
        self.write("docs/e.md", "---\nid: OPS-09\n")
        msgs = " | ".join(self.errors())
        self.assertIn("'last_reviewed' is a required property", msgs)
        self.assertIn("'superseded_by' is a required property", msgs)
        self.assertIn("does not match", msgs)
        self.assertIn("YAML does not parse", msgs)
        self.assertIn("never closed", msgs)

    def test_duplicate_ids_fail_templates_do_not(self) -> None:
        self.write("docs/ops/a.md", GOOD_FM)
        self.write("docs/ops/b.md", GOOD_FM)
        self.write("docs/templates/runbook.md", GOOD_FM)
        self.write("docs/templates/how-to.md", GOOD_FM)
        msgs = self.errors()
        self.assertEqual([m for m in msgs if "duplicate id" in m], ["duplicate id OPS-02 (also in docs/ops/a.md)"])

    def test_translation_shares_the_english_id(self) -> None:
        vi = GOOD_FM.replace("---\n\n#", "lang: vi\ntranslation_of: docs/ops/rollback.md\n---\n\n#")
        self.write("docs/ops/rollback.md", GOOD_FM)
        self.write("docs/ops/rollback.vi.md", vi)
        self.assertEqual(self.errors(), [])

    def test_translation_rules_fail(self) -> None:
        self.write("docs/ops/rollback.md", GOOD_FM)
        # wrong target, id differs from the English page, English page missing, lang missing
        self.write("docs/ops/rollback.vi.md",
                   GOOD_FM.replace("---\n\n#", "lang: vi\ntranslation_of: docs/ops/other.md\n---\n\n#"))
        self.write("docs/ops/b.vi.md", GOOD_FM.replace("OPS-02", "OPS-07").replace(
            "---\n\n#", "lang: vi\ntranslation_of: docs/ops/b.md\n---\n\n#"))
        self.write("docs/ops/c.md", GOOD_FM.replace("OPS-02", "OPS-08").replace("---\n\n#", "lang: vi\n---\n\n#"))
        msgs = " | ".join(self.errors())
        self.assertIn("translation_of must be docs/ops/rollback.md", msgs)
        self.assertIn("docs/ops/b.md, but that page is missing", msgs)
        self.assertIn("'translation_of' is a required property", msgs)
        self.assertIn("only a translation file", msgs)
        self.assertNotIn("duplicate id", msgs)

    def test_translation_helpers(self) -> None:
        self.assertEqual(docslib.translation_lang("docs/guides/ceo.vi.md"), "vi")
        self.assertIsNone(docslib.translation_lang("docs/guides/ceo.md"))
        self.assertIsNone(docslib.translation_lang("docs/.vi.md"))
        self.assertEqual(docslib.source_of_translation("docs/guides/ceo.vi.md"), "docs/guides/ceo.md")

    def test_freshness_report(self) -> None:
        self.write("docs/ops/rollback.md", GOOD_FM)
        pages, _ = check_frontmatter.load_pages(self.root)
        stale, untested = check_frontmatter.freshness(pages, dt.date(2027, 1, 1))
        self.assertEqual([(r["id"], r["due"]) for r in stale], [("OPS-02", "2026-11-18")])
        self.assertEqual([r["last_tested"] for r in untested], ["2026-01-01"])
        out = self.root / "out/freshness.md"
        check_frontmatter.write_report(out, stale, untested, len(pages), dt.date(2027, 1, 1))
        self.assertIn("| OPS-02 | `docs/ops/rollback.md` | 2026-10-19 | 2026-11-18 | 44 |", out.read_text())


class AiGatewayNamesTest(TempRepo):
    """AA-1042: the AI gateway guide's drift guard (check_ai_gateway_names.py). Invented stage, model, connection and
    secret names only."""

    SNAP = {
        "schema": "aa900-llm-routes/2",
        "routes": [{"stage": "q7_write"}, {"stage": "q7_judge"}, {"stage": "zp_compose"}],
        "models": [{"model_key": "zeta-5-5"}, {"model_key": "zeta-4-1"}, {"model_key": "omni-embed-v9"}],
        "connections": [{"connection_key": "acc8"}, {"connection_key": "zeta-direct"}],
        "deployments": [],
    }
    REGISTER = "# Secrets register\n\n| Name | App |\n|---|---|\n| `zz-llm/dev/zeta-direct` | cis |\n"

    def setUp(self) -> None:
        super().setUp()
        import json
        self.write("docs/generated/llm-routes.snapshot.json", json.dumps(self.SNAP))
        self.write("docs/security/secrets-register.md", self.REGISTER)

    def page(self, body: str, vi: str | None = None) -> None:
        self.write("docs/architecture/ai-gateway.md", body)
        self.write("docs/architecture/ai-gateway.vi.md", body if vi is None else vi)

    def messages(self) -> list[str]:
        findings, _ = check_ai_gateway_names.check(self.root)
        return [f"{f.path}:{f.line} {f.message}" for f in findings]

    def test_known_names_pass(self) -> None:
        self.page("Stage `q7_write` runs `zeta-5-5` on `zeta-direct`, then `acc8`; key `zz-llm/dev/zeta-direct`.\n"
                  "Not keys: `aws_only`, `model_first`, `shared.llm_role_config`, `zz-llm/<env>/`, `aa-x-dev-y`,\n"
                  "`/admin/ai-gateway`, `tools/x/shared/y.py`, `LLM_ROUTE_AWS_FIRST`.\n")
        findings, checked = check_ai_gateway_names.check(self.root)
        self.assertEqual(findings, [])
        self.assertEqual(checked, 10)    # 5 names per page, both pages

    def test_gone_stage_model_connection_and_secret_fail(self) -> None:
        self.page("Fine: `q7_judge`.\n", vi="Gone: `q7_atom_writer`, `zeta-9-9`, `zeta-indirect`, `acc1`,\n"
                  "`zz-llm/dev/missing-key`.\n")
        msgs = self.messages()
        self.assertEqual(len(msgs), 5, msgs)
        self.assertTrue(all(m.startswith("docs/architecture/ai-gateway.vi.md:") for m in msgs))
        self.assertIn("`q7_atom_writer` is not a stage", msgs[0])
        self.assertIn("`zeta-9-9` is neither a model nor a connection", msgs[1])
        self.assertIn("`acc1` is neither", msgs[3])
        self.assertIn("`zz-llm/dev/missing-key` has no row in docs/security/secrets-register.md", msgs[4])

    def test_code_fences_are_skipped(self) -> None:
        self.page("```text\n`q7_gone`\n```\nSee `q7_write`.\n")
        self.assertEqual(self.messages(), [])

    def test_snapshot_without_connections_fails_closed(self) -> None:
        import json
        self.write("docs/generated/llm-routes.snapshot.json",
                   json.dumps({k: v for k, v in self.SNAP.items() if k != "connections"}))
        self.page("`zeta-direct` and `q7_write`.\n")
        msgs = self.messages()
        self.assertEqual(len(msgs), 1, msgs)
        self.assertIn("no connection list", msgs[0])

    def test_missing_translation_fails(self) -> None:
        self.write("docs/architecture/ai-gateway.md", "`q7_write`\n")
        self.assertIn("the Vietnamese copy is missing", " ".join(self.messages()))

    def test_main_exit_codes(self) -> None:
        self.page("`q7_write`\n")
        self.assertEqual(self.run_quiet(check_ai_gateway_names.main, ["--root", str(self.root)]), 0)
        self.page("`q7_gone`\n")
        self.assertEqual(self.run_quiet(check_ai_gateway_names.main, ["--root", str(self.root)]), 1)


