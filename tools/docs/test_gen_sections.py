class Root(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.root = Path(self._tmp.name)
        self.put(g.PLATFORM, PLATFORM)
        self.put(g.INVENTORY, INVENTORY)
        self.put("docs/guides/pond.md", PAGE)

    def tearDown(self):
        self._tmp.cleanup()

    def put(self, rel: str, text: str) -> None:
        p = self.root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")

    def read(self, rel: str) -> str:
        return (self.root / rel).read_text(encoding="utf-8")


class CollectTest(Root):
    def test_inventory_services_cluster_and_apps(self):
        facts = g.collect(self.root)
        ecs = facts["ecs"]
        self.assertEqual(ecs["cluster"], "pond-cluster")
        self.assertEqual([(s["name"], s["app"]) for s in ecs["services"]],
                         [("river-dev-api", "Repo-River"), ("stone-dev-web", "Repo-Stone")])
        self.assertEqual(ecs["infra_commit"], "abcdef01")
        self.assertEqual(facts["accounts"][1]["terraform_root"], None)

    def test_platform_refuses_ids_and_mail(self):
        for bad in ("    decision: ADR 9001 for " + "4321" * 3 + "\n", "    decision: ask owl@example.invalid\n"):
            with self.subTest(bad=bad):
                with self.assertRaises(g.GenError):
                    g.parse_platform(PLATFORM.replace("    decision: ADR 9002\n", bad))

    def test_platform_shape(self):
        with self.assertRaises(g.GenError):
            g.parse_platform(PLATFORM.replace("version: 1", "version: 2"))
        with self.assertRaises(g.GenError):
            g.parse_platform(PLATFORM.replace("    order: [Owl API, hill (Bedrock)]\n", "    order: []\n"))

    def test_inventory_without_ecs_rows_fails(self):
        with self.assertRaises(g.GenError):
            g.parse_inventory("# empty\n", {})


class WriteCheckTest(Root):
    def test_write_then_check_is_clean(self):
        changed = g.write(self.root)
        self.assertEqual(changed, [g.SNAPSHOT, "docs/guides/pond.md"])
        page = self.read("docs/guides/pond.md")
        self.assertIn("| `river-dev-api` | Repo-River |", page)
        self.assertIn("Cluster `pond-cluster`, 2 services:", page)
        self.assertIn("<!-- gen:not-a-block -->\n```", page)          # the fenced marker is text, untouched
        self.assertEqual(g.check(self.root), ([], []))
        self.assertEqual(g.write(self.root), [g.SNAPSHOT])              # idempotent

    def test_hand_edit_of_a_block_fails(self):
        g.write(self.root)
        page = self.read("docs/guides/pond.md").replace("Repo-River", "Repo-Elsewhere")
        self.put("docs/guides/pond.md", page)
        errors, _ = g.check(self.root)
        self.assertEqual(len(errors), 1)
        self.assertIn("ecs-services", errors[0])

    def test_platform_change_without_write_fails(self):
        g.write(self.root)
        self.put(g.PLATFORM, PLATFORM.replace("hill is second", "hill is last"))
        errors, warnings = g.check(self.root)
        self.assertTrue(any("llm_routes" in e for e in errors))

    def test_inventory_change_only_warns(self):
        g.write(self.root)
        self.put(g.INVENTORY, INVENTORY.replace("river-dev-api", "river-dev-api2"))
        errors, warnings = g.check(self.root)
        self.assertEqual(errors, [])
        self.assertEqual(len(warnings), 1)

    def test_snapshot_with_an_account_id_fails(self):
        g.write(self.root)
        facts = json.loads(self.read(g.SNAPSHOT))
        facts["ecs"]["cluster"] = "pond-" + "5678" * 3
        self.put(g.SNAPSHOT, json.dumps(facts))
        errors, _ = g.check(self.root)
        self.assertTrue(errors and "account ID" in errors[0])

    def test_missing_snapshot_fails(self):
        errors, _ = g.check(self.root)
        self.assertIn("missing", errors[0])

    def test_unknown_unclosed_and_nested_blocks_fail(self):
        g.write(self.root)
        for body, needle in (("<!-- gen:no-such -->\n<!-- /gen -->\n", "unknown block"),
                             ("<!-- gen:accounts -->\n", "never closed"),
                             ("<!-- gen:accounts -->\n<!-- gen:ecs-services -->\n<!-- /gen -->\n", "no nesting"),
                             ("<!-- /gen -->\n", "without an open block")):
            with self.subTest(needle=needle):
                self.put("docs/other.md", "# Other\n\n" + body)
                errors, _ = g.check(self.root)
                self.assertTrue(any(needle in e for e in errors), errors)

    def test_journals_are_not_scanned(self):
        g.write(self.root)
        self.put("docs/sessions/2026-01-01-x.md", "<!-- gen:no-such -->\n")
        self.assertEqual(g.check(self.root), ([], []))


class RenderTest(Root):
    def test_links_follow_the_page_depth(self):
        facts = g.collect(self.root)
        self.assertIn("](generated/llm-routes.md)", g.render("llm-route-order", facts, "docs/top.md"))
        self.assertIn("](../generated/llm-routes.md)", g.render("llm-route-order", facts, "docs/guides/pond.md"))
        self.assertIn("](../../docs/generated/llm-routes.md)", g.render("llm-route-order", facts, "skill/x/SKILL.md"))

    def test_accounts_table(self):
        text = g.render("accounts", g.collect(self.root))
        self.assertIn("| lake | lake-main | Every workload of the lake | No | `accounts/lake` | Live | ADR 9001 |", text)
        self.assertIn("| hill | hill-ai | One invoker role | Yes, first | none | Live | ADR 9002 |", text)

    def test_route_order(self):
        self.assertIn("| Owl | Owl API → hill (Bedrock) | hill is second |",
                      g.render("llm-route-order", g.collect(self.root)))

    def test_main_check_exit_codes(self):
        self.assertEqual(g.main(["--write", "--root", str(self.root)]), 0)
        self.assertEqual(g.main(["--check", "--root", str(self.root)]), 0)
        self.put("docs/guides/pond.md", self.read("docs/guides/pond.md").replace("Repo-River", "Repo-Elsewhere"))
        self.assertEqual(g.main(["--check", "--root", str(self.root)]), 1)


